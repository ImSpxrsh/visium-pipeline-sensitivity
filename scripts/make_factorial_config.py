"""
Write configs/multiverse_full.yaml: the full Cartesian product of the axes in
Table I of the paper (3 x 2 x 3 x 2 x 3 x 2 x 4 = 864 specs).

The curated 30-spec set is centered on one canonical pipeline, so its Type-II
ANOVA shares depend on which combinations were picked. The full factorial is
balanced, so every axis gets an equal number of runs at each level. It is meant
to be run on a cluster (see COMPUTE.md); serially it would take days.

Usage:  python scripts/make_factorial_config.py
"""
import itertools
from pathlib import Path

import yaml

PROJECT = Path(__file__).resolve().parent.parent
OUT = PROJECT / "configs" / "multiverse_full.yaml"

AXES = {
    "normalization": ["log1p", "sqrt", "total"],
    "hvg_method": ["seurat", "scanpy"],
    "hvg_n": [2000, 3000, 5000],
    "pcs": [30, 50],
    "k": [6, 10, 15],
    "cluster": ["leiden", "louvain"],
    "resolution": [0.3, 0.5, 0.8, 1.2],
}


def main() -> None:
    specs = []
    for norm, hm, hn, pcs, k, cl, res in itertools.product(*AXES.values()):
        specs.append({
            "name": f"{norm}_{hm}{hn}_pc{pcs}_k{k}_{cl}{res}",
            "normalization": norm,
            "feature_selection": {"method": hm, "n_genes": hn},
            "dimensionality_reduction": {"n_components": pcs},
            "neighborhood_graph": {"type": "knn", "k_or_radius": k},
            "clustering": {"method": cl, "resolution": res},
            "spatially_variable_genes": {"method": "morans_i"},
            "cell_cell_communication": {"enabled": False},
        })
    config = {
        "global": {"random_state": 42, "n_jobs": 1, "verbose": True},
        "specs": specs,
    }
    header = (
        "# Full factorial specification space (auto-generated by\n"
        "# scripts/make_factorial_config.py -- do not edit by hand).\n"
        f"# {len(specs)} specs. Run on a cluster; see COMPUTE.md.\n"
    )
    OUT.write_text(header + yaml.safe_dump(config, sort_keys=False))
    print(f"Wrote {len(specs)} specs to {OUT}")


if __name__ == "__main__":
    main()
